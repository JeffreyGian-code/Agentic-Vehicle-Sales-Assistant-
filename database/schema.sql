-- Schema matching the imported Aurion backup (PostgreSQL 18).
-- Loaded before seed.sql on fresh Docker volumes and in CI.
CREATE TABLE IF NOT EXISTS public.vehicles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model varchar(120) CONSTRAINT vehicles_name_not_null NOT NULL,
    brand varchar(60) NOT NULL,
    price integer NOT NULL CHECK (price >= 0),
    vehicle_type varchar(40) NOT NULL,
    variant varchar(100),
    CONSTRAINT vehicles_brand_model_variant_unique UNIQUE (brand, model, variant)
);
CREATE TABLE IF NOT EXISTS public.vehicles_backup (
    id integer,
    model varchar(120),
    brand varchar(60),
    price integer,
    vehicle_type varchar(40),
    variant varchar(100)
);
CREATE INDEX IF NOT EXISTS vehicles_brand_lower_idx ON public.vehicles (lower(brand));
CREATE INDEX IF NOT EXISTS vehicles_price_idx ON public.vehicles (price);
CREATE INDEX IF NOT EXISTS vehicles_type_lower_idx ON public.vehicles (lower(vehicle_type));
